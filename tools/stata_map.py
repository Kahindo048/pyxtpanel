"""Generate docs/stata_map.md: Stata command -> Python function, return codes, reproduced quirks.

    python -m tools.stata_map            # check that the file is up to date
    python -m tools.stata_map --write    # rewrite it

The table is built from the registries (operators, descriptions), a short list of structural
commands, the table of Stata return codes and the ``# STATA-QUIRK:`` comments of the code, so
adding a feature updates the map without editing it by hand.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "stata_map.md"

#: Structural commands that are not in a registry.
STRUCTURAL = [
    ("xtset id t, delta()", "`xtset(frame, id, time, delta=)`"),
    ("tsset / tsfill", "`PanelData.tsfill()`"),
    ("tsfill, full", "`PanelData.tsfill(full=True)`"),
    ("duplicates report / list", "`duplicates(frame, id, time)`"),
    ("use / save (xtset kept)", "`read_stata(path)` / `PanelData.to_stata(path)`"),
    ("if / in", "`PanelData.select(where=, units=, periods=, complete=)`"),
    ("markout", "`PanelData.select(complete=[...])`"),
    ("L. F. D. S. LD. L(1/3).", "`PanelData.operate(*terms)`, `lag`, `lead`, `diff`, `seasonal`"),
    (
        "xtdata, fe / be",
        "`PanelData.within(add_mean=True, listwise=True)` / `between(listwise=True)`",
    ),
]


def quirks() -> list[tuple[str, str, str]]:
    """``(file, marker, text)`` of every provenance comment in the sources."""
    found = []
    for path in sorted((ROOT / "src" / "pyxtpanel").rglob("*.py")):
        relative = path.relative_to(ROOT / "src").as_posix()
        for line in path.read_text(encoding="utf-8").splitlines():
            match = re.match(r"\s*# (STATA-QUIRK|Stata):\s*(.+)", line)
            if match:
                found.append((relative, match.group(1), match.group(2).strip()))
    return found


def render() -> str:
    """Return the Markdown text of the map."""
    from pyxtpanel._errors import STATA_CODES
    from pyxtpanel.describe._spec import DESCRIPTIONS
    from pyxtpanel.ops._spec import OPERATORS

    lines = [
        "# Stata map",
        "",
        "Generated by `python -m tools.stata_map --write`; do not edit by hand.",
        "",
        "## Commands",
        "",
        "| Stata | Python |",
        "|---|---|",
        *(f"| `{stata}` | {python} |" for stata, python in STRUCTURAL),
    ]
    for name, spec in DESCRIPTIONS.specs():
        label = f"`{spec.stata}`" if spec.stata else "*(addition of the package)*"
        lines.append(f"| {label} | `PanelData.{name}()` |")
    for name, spec in OPERATORS.specs():
        label = f"`{spec.stata}`" if spec.stata else "*(addition of the package)*"
        lines.append(f'| {label} | `PanelData.transform("{name}", ...)` |')
    from pyxtpanel.plot._spec import KINDS

    for name, spec in KINDS.specs():
        label = f"`{spec.stata}`" if spec.stata else "*(addition of the package)*"
        lines.append(f'| {label} | `PanelData.plot("{name}", ...)` |')
    from pyxtpanel.explore._spec import TOOLS

    for name, spec in TOOLS.specs():
        label = f"`{spec.stata}`" if spec.stata else "*(addition of the package)*"
        call = f"`PanelData.{name}()`" if spec.on_panel else f"`{name}(frame, ...)`"
        lines.append(f"| {label} | {call} |")
    from pyxtpanel.diagnostics._core.spec import TESTS

    for name, spec in TESTS.specs():
        commands = ", ".join(f"`{c.strip()}`" for c in spec.stata.split(";"))
        lines.append(f'| {commands} | `run_test("{name}", ...)` |')
    lines += ["", "## Return codes kept", "", "| Code | Meaning |", "|---:|---|"]
    lines += [f"| {code} | {text} |" for code, text in sorted(STATA_CODES.items())]
    lines += ["", "## Behaviours of Stata reproduced on purpose", ""]
    lines += [f"- `{path}`: {text}" for path, marker, text in quirks() if marker == "STATA-QUIRK"]
    lines += ["", "## Provenance notes", ""]
    lines += [f"- `{path}`: {text}" for path, marker, text in quirks() if marker == "Stata"]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--write" in argv:
        TARGET.parent.mkdir(exist_ok=True)
        TARGET.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET}")
        return 0
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if current != text:
        print("docs/stata_map.md is out of date: run python -m tools.stata_map --write")
        return 1
    print("docs/stata_map.md is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
